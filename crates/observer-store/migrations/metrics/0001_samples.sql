-- The statistics, apart from Observer's state: a sample every five seconds, kept 72 hours, and
-- aggregates of every minute (30 days) and every hour (kept), always computed from the samples.
-- A column is NULL when its measure was not taken, never 0. Timestamps are Unix seconds.

-- One row per five-second slot, under the slot's start.
CREATE TABLE sample_5s (
    ts                      INTEGER PRIMARY KEY,
    state                   TEXT    NOT NULL CHECK (state IN ('stopped', 'starting', 'online', 'degraded',
                                'hung', 'stopping', 'crashed', 'crash_loop')),
    -- Clients connected, from /dynamic.json.
    players                 INTEGER,
    -- sv_maxclients.
    slots                   INTEGER,
    ping_avg_ms             REAL,
    ping_p95_ms             INTEGER,
    ping_max_ms             INTEGER,
    -- Net ids new since the previous list of the run.
    joins                   INTEGER,
    leaves                  INTEGER,
    -- Per thread: ticks in the slot, the milliseconds they took, and those over the thread's budget.
    main_ticks              INTEGER,
    main_tick_ms            INTEGER,
    main_over               INTEGER,
    network_ticks           INTEGER,
    network_tick_ms         INTEGER,
    network_over            INTEGER,
    sync_ticks              INTEGER,
    sync_tick_ms            INTEGER,
    sync_over               INTEGER,
    hitch_main              INTEGER,
    hitch_network           INTEGER,
    hitch_sync              INTEGER,
    -- Watchdog barks.
    barks                   INTEGER,
    -- The longest hitch of the slot.
    hitch_max_ms            INTEGER,
    -- Started resources, as the bridge reports them.
    resources               INTEGER,
    js_heap_used            INTEGER,
    js_heap_total           INTEGER,
    -- FXServer's main process: percent of one core, bytes, and bytes per second through the I/O system.
    fxs_cpu                 REAL,
    fxs_ws                  INTEGER,
    fxs_private             INTEGER,
    fxs_threads             INTEGER,
    fxs_handles             INTEGER,
    fxs_read_bps            REAL,
    fxs_write_bps           REAL,
    -- The processes FXServer started, together.
    children                INTEGER,
    children_cpu            REAL,
    children_ws             INTEGER,
    children_private        INTEGER,
    -- Percent of the whole machine.
    host_cpu                REAL,
    host_mem_used           INTEGER,
    host_mem_total          INTEGER,
    -- The volume of Observer's data folder.
    host_disk_free          INTEGER,
    host_disk_total         INTEGER,
    host_rx_bps             REAL,
    host_tx_bps             REAL,
    -- Observer itself.
    obs_cpu                 REAL,
    obs_ws                  INTEGER,
    obs_private             INTEGER,
    obs_state_db            INTEGER,
    obs_metrics_db          INTEGER,
    obs_ws_clients          INTEGER,
    -- How long the sampler took to gather the sample.
    collect_ms              INTEGER
) STRICT;

