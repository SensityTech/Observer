-- Each spawn of FXServer. Generations start again at 1 with each Observer, so a run is known by
-- the Observer that started it and its generation. Times are Unix milliseconds.
CREATE TABLE server_run (
    id               INTEGER PRIMARY KEY,
    observer_started INTEGER NOT NULL,
    generation       INTEGER NOT NULL,
    started_ms       INTEGER NOT NULL,
    ready_ms         INTEGER,
    ended_ms         INTEGER,
    start_cause      TEXT    NOT NULL CHECK (start_cause IN ('requested', 'restart', 'recovery')),
    end_cause        TEXT    CHECK (end_cause IN ('stopped', 'crashed', 'hung', 'lost')),
    build            INTEGER,
    UNIQUE (observer_started, generation)
) STRICT;

CREATE INDEX server_run_started ON server_run (started_ms);
