//! What changed on the server between two of its starts: what each start ran from, how two of them
//! compare, and the rules that only depend on those records. Paths are relative to the server's
//! data folder, `/`-separated (`resources/[qb]/qb-core/fxmanifest.lua`).

use serde::{Deserialize, Serialize};
use ts_rs::TS;

use crate::files::{NEVER_SHOW, glob_matches};

/// The extensions whose files get line diffs, until the owner changes the list.
pub const DEFAULT_EXTENSIONS: &[&str] = &[
    "lua", "js", "mjs", "cjs", "ts", "tsx", "jsx", "vue", "svelte", "json", "jsonc", "cfg", "txt", "md",
    "yml", "yaml", "toml", "ini", "xml", "meta", "html", "htm", "css", "scss", "sql", "cs", "csv",
];

/// Files FXServer never loads, listed by size and time and never read.
pub const ARCHIVE_EXTENSIONS: &[&str] = &["zip", "rar", "7z"];

/// Files generated by a package manager: hashed, never stored, whatever their extension.
pub const LOCKFILES: &[&str] = &["package-lock.json", "yarn.lock", "pnpm-lock.yaml"];

/// The largest text the owner may have kept whole.
pub const MAX_TEXT_LIMIT: u64 = 8 * 1024 * 1024;

/// The owner's settings of file changes. `GET` and `PUT /servers/default/changes/settings`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
#[ts(export)]
pub struct ChangesSettings {
    /// A snapshot at each start.
    pub enabled: bool,
    /// Extensions whose files may get line diffs, lower case and without the dot.
    pub extensions: Vec<String>,
    /// Globs of what is never walked.
    pub excluded: Vec<String>,
    /// Globs of files whose contents are never stored nor shown.
    pub hidden: Vec<String>,
    /// The largest text kept whole, in bytes.
    pub max_text: u64,
    /// The bytes of stored texts, compressed, past which the oldest are dropped.
    pub budget: u64,
    pub retention_days: u32,
    /// Bytes read each second at most, while the server runs.
    pub hash_rate: u64,
    /// Days between two full verifications; 0 for none.
    pub verify_days: u32,
    /// Minutes between two checks of the disk while the server runs; 0 for none.
    pub drift_minutes: u32,
    /// Raise `observer:startChanges` once per run.
    pub start_event: bool,
}

impl Default for ChangesSettings {
    fn default() -> Self {
        Self {
            enabled: true,
            extensions: DEFAULT_EXTENSIONS
                .iter()
                .map(|&extension| extension.to_owned())
                .collect(),
            excluded: Vec::new(),
            hidden: Vec::new(),
            max_text: 1024 * 1024,
            budget: 2_000_000_000,
            retention_days: 180,
            hash_rate: 64_000_000,
            verify_days: 7,
            drift_minutes: 0,
            start_event: true,
        }
    }
}

/// What a file is, which decides what is kept of it and how two versions compare. Stored by name.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub enum FileKind {
    /// Its masked contents are kept and compared line by line.
    Text,
    /// Minified, bundled or a lockfile: compared by size and hash.
    Generated,
    /// Encrypted by the Cfx.re escrow, never decrypted.
    Encrypted,
    Binary,
    /// On the never-show list or one of the owner's hidden globs: its contents are never stored.
    Hidden,
    /// An archive FXServer never loads, compared by size and time.
    Archive,
    /// A cloud placeholder or another reparse point that reading would recall: never read.
    Offline,
    /// A link that is not followed, compared by its target.
    Link,
    Unreadable,
}

impl FileKind {
    pub const ALL: [Self; 9] = [
        Self::Text,
        Self::Generated,
        Self::Encrypted,
        Self::Binary,
        Self::Hidden,
        Self::Archive,
        Self::Offline,
        Self::Link,
        Self::Unreadable,
    ];

    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Text => "text",
            Self::Generated => "generated",
            Self::Encrypted => "encrypted",
            Self::Binary => "binary",
            Self::Hidden => "hidden",
            Self::Archive => "archive",
            Self::Offline => "offline",
            Self::Link => "link",
            Self::Unreadable => "unreadable",
        }
    }

    pub fn from_name(name: &str) -> Option<Self> {
        Self::ALL.into_iter().find(|kind| kind.as_str() == name)
    }

    /// Whether its plain SHA-256 may be shown: never for text or hidden files, whose short
    /// secrets a plain hash would let anyone guess offline.
    pub const fn shows_hash(self) -> bool {
        matches!(self, Self::Generated | Self::Encrypted | Self::Binary)
    }
}

/// What a snapshot records: a start of FXServer, or the disk as it was when someone checked it.
