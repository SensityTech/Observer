#[ts(export)]
pub struct Manifest {
    /// `fxmanifest.lua`, or `__resource.lua` for an old resource.
    pub file: String,
    pub version: Option<String>,
    pub fx_version: Option<String>,
    pub games: Vec<String>,
    pub author: Option<String>,
    pub description: Option<String>,
    pub lua54: Option<String>,
    /// The directives whose value the manifest computes, such as `version`.
    pub computed: Vec<String>,
}

impl Manifest {
    /// The version as two resources compare it: computed values compare equal to each other.
    pub fn compared_version(&self) -> (Option<&str>, bool) {
        (
            self.version.as_deref(),
            self.computed.iter().any(|name| name == "version"),
        )
    }
}

