//! What changed on the server between two of its starts: what each start ran from, how two of them
//! compare, and the rules that only depend on those records. Paths are relative to the server's
//! data folder, `/`-separated (`resources/[qb]/qb-core/fxmanifest.lua`).

use serde::{Deserialize, Serialize};
use ts_rs::TS;

use crate::files::{NEVER_SHOW, glob_matches};

/// The extensions whose files get line diffs, until the owner changes the list.
pub const DEFAULT_EXTENSIONS: &[&str] = &[
    "lua", "js", "mjs", "cjs", "ts", "tsx", "jsx", "vue", "svelte", "json", "jsonc", "cfg", "txt", "md",
    "yml", "yaml", "toml", "ini", "xml", "meta", "html", "htm", "css", "scss", "sql", "cs", "csv",
];

/// Files FXServer never loads, listed by size and time and never read.
pub const ARCHIVE_EXTENSIONS: &[&str] = &["zip", "rar", "7z"];

/// Files generated by a package manager: hashed, never stored, whatever their extension.
pub const LOCKFILES: &[&str] = &["package-lock.json", "yarn.lock", "pnpm-lock.yaml"];

/// What a file is, which decides what is kept of it and how two versions compare. Stored by name.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub enum FileKind {
    /// Its masked contents are kept and compared line by line.
    Text,
    /// Minified, bundled or a lockfile: compared by size and hash.
    Generated,
    /// Encrypted by the Cfx.re escrow, never decrypted.
    Encrypted,
    Binary,
    /// On the never-show list or one of the owner's hidden globs: its contents are never stored.
    Hidden,
    /// An archive FXServer never loads, compared by size and time.
    Archive,
    /// A cloud placeholder or another reparse point that reading would recall: never read.
    Offline,
    /// A link that is not followed, compared by its target.
    Link,
    Unreadable,
}

impl FileKind {
    pub const ALL: [Self; 9] = [
        Self::Text,
        Self::Generated,
        Self::Encrypted,
        Self::Binary,
        Self::Hidden,
        Self::Archive,
        Self::Offline,
        Self::Link,
        Self::Unreadable,
    ];

    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Text => "text",
            Self::Generated => "generated",
            Self::Encrypted => "encrypted",
            Self::Binary => "binary",
            Self::Hidden => "hidden",
            Self::Archive => "archive",
            Self::Offline => "offline",
            Self::Link => "link",
            Self::Unreadable => "unreadable",
        }
    }

    pub fn from_name(name: &str) -> Option<Self> {
        Self::ALL.into_iter().find(|kind| kind.as_str() == name)
    }

    /// Whether its plain SHA-256 may be shown: never for text or hidden files, whose short
    /// secrets a plain hash would let anyone guess offline.
    pub const fn shows_hash(self) -> bool {
        matches!(self, Self::Generated | Self::Encrypted | Self::Binary)
    }
}

/// What a resource's manifest says, read as text and never run. Each value is the first the
/// manifest gives, at most 256 characters; one the manifest computes in Lua is listed in
/// `computed` instead.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct Manifest {
    /// `fxmanifest.lua`, or `__resource.lua` for an old resource.
    pub file: String,
    pub version: Option<String>,
    pub fx_version: Option<String>,
    pub games: Vec<String>,
    pub author: Option<String>,
    pub description: Option<String>,
    pub lua54: Option<String>,
    /// The directives whose value the manifest computes, such as `version`.
    pub computed: Vec<String>,
}

impl Manifest {
    /// The version as two resources compare it: computed values compare equal to each other.
    pub fn compared_version(&self) -> (Option<&str>, bool) {
        (
            self.version.as_deref(),
            self.computed.iter().any(|name| name == "version"),
        )
    }
}

/// Where a resource held in git stands: its branch, or none when the head is detached, and the
/// commit. Nothing else of the repository is read.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct GitHead {
    pub branch: Option<String>,
    pub commit: Option<String>,
}

/// An npm package a resource holds in a `node_modules` folder.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct Package {
    pub name: String,
    pub version: Option<String>,
}

/// Whether one of the owner's globs covers `path`. A glob with `/` is a path from the data folder,
/// matched one component at a time, and covers what lies below it; one without `/` matches a file
/// or folder name anywhere. `*` and `?` are the only wildcards and `[` `]` stand for themselves,
/// since FiveM names its categories `[maps]`. Names compare without case, as a refusal should.
pub fn glob_covers(glob: &str, path: &str) -> bool {
    let glob = glob.trim_matches('/');
    if glob.is_empty() {
        return false;
    }
    if glob.contains('/') {
        let mut components = path.split('/');
        glob.split('/').all(|part| {
            components
                .next()
                .is_some_and(|name| glob_matches(part, name, true))
        })
    } else {
        path.split('/').any(|name| glob_matches(glob, name, true))
    }
}

/// Whether a glob the owner typed can be used: not empty, no `**`, no `..` and no backslash or
/// drive, so that it reads the same on both systems.
pub fn valid_glob(glob: &str) -> bool {
    let glob = glob.trim_matches('/');
    !glob.is_empty()
        && glob.len() <= 1024
        && !glob.contains("**")
        && !glob.contains(['\\', ':', '\0'])
        && !glob.chars().any(char::is_control)
        && glob
            .split('/')
            .all(|part| !part.is_empty() && part != "." && part != "..")
}

/// Whether the contents of the file at `path` are never stored nor shown: a name on the list shared
/// with file access, anywhere in the path, or one of the owner's hidden globs.
pub fn hidden(path: &str, globs: &[String]) -> bool {
    path.split('/')
        .any(|name| NEVER_SHOW.iter().any(|glob| glob_matches(glob, name, true)))
        || globs.iter().any(|glob| glob_covers(glob, path))
}

/// The extension that decides whether a file may be text, in lower case.
pub fn extension(path: &str) -> Option<String> {
    let name = path.rsplit('/').next()?;
    let (stem, extension) = name.rsplit_once('.')?;
    (!stem.is_empty()).then(|| extension.to_ascii_lowercase())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_glob_with_a_slash_is_a_path_from_the_data_folder_and_covers_what_lies_below() {
        let glob = "resources/[core]/my_bot";

        assert!(glob_covers(glob, "resources/[core]/my_bot/config/secrets.lua"));
        assert!(glob_covers(glob, "resources/[core]/my_bot"));
        assert!(!glob_covers(glob, "resources/[core]/my_bots/config.lua"));
        assert!(!glob_covers(glob, "resources/my_bot/config.lua"));
        assert!(glob_covers(
            "resources/*/my_bot/*.lua",
            "resources/[x]/My_Bot/main.lua"
        ));
    }

    #[test]
    fn a_glob_without_a_slash_matches_a_name_anywhere() {
        assert!(glob_covers("secrets.lua", "resources/a/config/secrets.lua"));
        assert!(glob_covers("config", "resources/a/config/secrets.lua"));
        assert!(glob_covers("*.sql", "resources/a/install.SQL"));
        assert!(!glob_covers("secrets.lua", "resources/a/config/secrets.lua.bak"));
    }

    #[test]
    fn brackets_in_a_glob_are_literal() {
        assert!(glob_covers("[maps]", "resources/[maps]/island/stream/a.ymap"));
        assert!(!glob_covers("[maps]", "resources/m/a.lua"));
    }

    #[test]
    fn the_shared_never_show_names_hide_a_file_anywhere() {
        assert!(hidden("resources/a/.env", &[]));
        assert!(hidden("resources/a/.env.production", &[]));
        assert!(hidden("resources/a/keys/server.pem", &[]));
        assert!(hidden("resources/a/txData/default/config.json", &[]));
        assert!(hidden("resources/a/vault.KDBX", &[]));
        assert!(!hidden("resources/a/client.lua", &[]));
        assert!(hidden("resources/a/client.lua", &["client.lua".to_owned()]));
    }

    #[test]
    fn globs_that_would_read_differently_on_either_system_are_refused() {
        assert!(valid_glob("resources/[core]/my_bot/config/secrets.lua"));
        assert!(valid_glob("*.secret"));
        for glob in ["", "/", "**/x", "a/../b", "C:/x", "a\\b", "a//b", "a/./b"] {
            assert!(!valid_glob(glob), "{glob:?}");
        }
    }

    #[test]
    fn the_extension_is_lower_case_and_a_dot_file_has_none() {
        assert_eq!(extension("resources/a/Client.LUA").as_deref(), Some("lua"));
        assert_eq!(extension("resources/a/.env"), None);
        assert_eq!(extension("resources/a/LICENSE"), None);
        assert_eq!(extension("resources/a.b/LICENSE"), None);
    }

    #[test]
    fn file_kinds_round_trip_by_name() {
        for kind in FileKind::ALL {
            assert_eq!(FileKind::from_name(kind.as_str()), Some(kind));
        }
    }
}
